-- B) clientes_tarifas -----------------------------------------
CREATE TABLE IF NOT EXISTS clientes_tarifas (
  id BIGSERIAL PRIMARY KEY,
  cliente TEXT NOT NULL,
  categoria_vehiculo TEXT NOT NULL,
  servicio TEXT NOT NULL,
  precio_neto INTEGER,
  activo BOOLEAN DEFAULT TRUE,
  fecha_actualizacion TIMESTAMP DEFAULT NOW(),
  UNIQUE (cliente, categoria_vehiculo, servicio)
);

CREATE INDEX IF NOT EXISTS idx_clientes_tarifas_cliente ON clientes_tarifas (cliente);
CREATE INDEX IF NOT EXISTS idx_clientes_tarifas_servicio ON clientes_tarifas (servicio);

ALTER TABLE clientes_tarifas ENABLE ROW LEVEL SECURITY;
DROP POLICY IF EXISTS "clientes_tarifas_all" ON clientes_tarifas;
CREATE POLICY "clientes_tarifas_all" ON clientes_tarifas FOR ALL USING (true) WITH CHECK (true);

-- C) estados_pago (se usa en Fase 2) --------------------------
CREATE TABLE IF NOT EXISTS estados_pago (
  id BIGSERIAL PRIMARY KEY,
  cliente TEXT NOT NULL,
  n_edp_cliente INTEGER NOT NULL,
  rut_cliente TEXT,
  periodo_desde DATE NOT NULL,
  periodo_hasta DATE NOT NULL,
  n_cotizacion_kame TEXT,
  solicitante TEXT,
  total_neto NUMERIC,
  iva NUMERIC,
  total NUMERIC,
  estado TEXT DEFAULT 'borrador',
  fecha_emision TIMESTAMP,
  fecha_envio TIMESTAMP,
  fecha_pago TIMESTAMP,
  observaciones TEXT,
  created_at TIMESTAMP DEFAULT NOW(),
  updated_at TIMESTAMP DEFAULT NOW(),
  UNIQUE (cliente, n_edp_cliente)
);

CREATE INDEX IF NOT EXISTS idx_estados_pago_cliente ON estados_pago (cliente);
CREATE INDEX IF NOT EXISTS idx_estados_pago_periodo_desde ON estados_pago (periodo_desde);
CREATE INDEX IF NOT EXISTS idx_estados_pago_estado ON estados_pago (estado);

ALTER TABLE estados_pago ENABLE ROW LEVEL SECURITY;
DROP POLICY IF EXISTS "estados_pago_all" ON estados_pago;
CREATE POLICY "estados_pago_all" ON estados_pago FOR ALL USING (true) WITH CHECK (true);

